/* Generates architecture.md (Mermaid) from lib/config.ts: `npm run diagram`. */
import * as fs from 'fs';
import * as path from 'path';
import { BUS_NAME, JCL_MAPPING, PROGRESSION_SCHEDULE, QUEUES, SERVICES } from '../lib/config';

const id = (s: string) => s.replace(/[^A-Za-z0-9]/g, '_');
const lines: string[] = [];
lines.push('flowchart LR');
lines.push('  subgraph Legacy["Legacy: jcl/LICNIGHT.jcl (COBOL batch)"]');
lines.push('    direction TB');
JCL_MAPPING.forEach((s, i) => {
  lines.push(`    ${s.step}["${s.step} ${s.program}<br/>${s.legacy.replace(/"/g, "'")}"]`);
  if (i > 0) lines.push(`    ${JCL_MAPPING[i - 1].step} --> ${s.step}`);
});
lines.push('  end');
lines.push('  subgraph AWS["LICSYS Next on AWS (ap-southeast-2)"]');
lines.push('    UI["LICSYS Next UI"] --> APIGW["API Gateway HTTP API<br/>Cognito JWT authorizer"]');
lines.push('    APIGW -- "VPC link" --> ALB["Internal ALB<br/>path routing"]');
lines.push(`    SCHED["EventBridge Scheduler<br/>${PROGRESSION_SCHEDULE.expression} ${PROGRESSION_SCHEDULE.timezone}"] --> TRIG["Lambda progression-trigger"]`);
lines.push(`    TRIG -- "POST ${PROGRESSION_SCHEDULE.path}" --> ALB`);
lines.push(`    BUS(("EventBridge<br/>${BUS_NAME}"))`);
lines.push('    subgraph ECS["ECS Fargate cluster licsys"]');
for (const s of SERVICES) lines.push(`      ${id(s.name)}["${s.name} :${s.port}<br/>${s.context}${s.rules.length ? '<br/>' + s.rules.join(', ') : ''}"]`);
lines.push('    end');
for (const s of SERVICES) {
  lines.push(`    ALB --> ${id(s.name)}`);
  lines.push(`    ${id(s.name)} --> ${id(s.table.name)}[("DynamoDB ${s.table.name}<br/>pk ${s.table.partitionKey}")]`);
  lines.push(`    ${id(s.name)} -- "${s.eventSource}" --> BUS`);
}
for (const q of QUEUES) {
  const label = q.pattern.detailType ? q.pattern.detailType.join(', ') : `source prefix ${q.pattern.sourcePrefix}`;
  lines.push(`    BUS -- "${label}" --> ${id(q.name)}[["SQS ${q.name}<br/>+ ${q.name}-dlq"]]`);
  const consumer = SERVICES.find((s) => s.consumes.includes(q.name))!;
  lines.push(`    ${id(q.name)} --> ${id(consumer.name)}`);
}
lines.push('    CW["CloudWatch dashboard licsys-next<br/>alarms -> SNS licsys-alarms"]');
lines.push('  end');
lines.push('  STEP010 -. "replaced by" .-> licence_service & demerit_service');
lines.push('  STEP020 -. "replaced by" .-> SCHED');
lines.push('  STEP030 -. "replaced by" .-> registration_service');

const table = ['| JCL step | Program | Legacy behaviour | LICSYS Next |', '|---|---|---|---|',
  ...JCL_MAPPING.map((s) => `| ${s.step} | ${s.program} | ${s.legacy} | ${s.modern} |`)];

const md = `# LICSYS Next: production architecture

*Fictional demo system. Generated by \`npm run diagram\` from \`lib/config.ts\`; do not edit by hand.*

\`\`\`mermaid
${lines.join('\n')}
\`\`\`

## Legacy JCL steps -> AWS components

${table.join('\n')}

The legacy step order (DMRPTS before LICUPG, \`COND=(0,NE,STEP010)\`) becomes an ordering guarantee in the new system:
offences post in real time and \`DemeritPointsChanged\` updates licence-service's points projection long before the
nightly progression sweep runs at ${PROGRESSION_SCHEDULE.expression} ${PROGRESSION_SCHEDULE.timezone} (LICNIGHT ran after the
~01:30 offence feed landed). Failed runs retry 3 times, then land in \`licsys-progression-schedule-dlq\` and alarm.

## Event routing (\`${BUS_NAME}\`)

| Rule | Queue (DLQ) | Receives | Consumer |
|---|---|---|---|
${QUEUES.map((q) => `| to-${q.name} | ${q.name} (${q.name}-dlq) | ${q.pattern.detailType ? q.pattern.detailType.join(', ') : 'all events, source prefix `' + q.pattern.sourcePrefix + '`'} | ${SERVICES.find((s) => s.consumes.includes(q.name))!.name} |`).join('\n')}
`;
fs.writeFileSync(path.join(__dirname, '..', 'architecture.md'), md);
console.log('wrote architecture.md');
